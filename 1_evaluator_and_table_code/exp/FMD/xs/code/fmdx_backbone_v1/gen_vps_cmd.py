#!/usr/bin/env python3
"""VPS RTX 4090 runner cmd for one FMDX backbone arm (lane 'vps'; runner dir-queue, numbers 400-499 reserved for FMDX).

The cmd: race lock (atomic mkdir of stage\\exp\\FMD\\xs\\race\\<arm>, owner 'vps'; lost -> RACE_LOST.json, exit 0) -> train
(bb_train.py, 1 process; batch layout fixed by DECISION_RECORD_backbone.md for a < 40 GB GPU: 32 x accum 16 = 512 sequences
per step, prereg A6) with the verdict mirror stage\\exp\\FMD\\xs\\verdicts\\verdict_<fm>.json (A4.3 c) -> FM-free val250 sampling
of every milestone on the 4 LUO val sets (bb_sample.py, seed 0, DDIM-50, eta 0, EMA; the training lane, A4.3 d). Scoring and
milestone selection run on CLUSTER-A after the run dir is pulled (sha-checked). Paths: stage\\<CLUSTER-A-relative path>; code at
code\\fmdx_backbone_v1 (unpacked tar, SHA256SUMS checked by the cmd).
Usage: python3 gen_vps_cmd.py ARM_ID NUMBER --arms arms.tsv > NNN_fx_<arm>.cmd
"""
import argparse
import csv


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("arm"); ap.add_argument("number", type=int)
    ap.add_argument("--arms", required=True)
    a = ap.parse_args()
    assert 400 <= a.number <= 499
    r = {x["arm_id"]: x for x in csv.DictReader(open(a.arms), delimiter="\t")}[a.arm]
    win = lambda p: "%STG%\\" + p.replace("$U/", "").replace("/", "\\") if p not in ("-", "") else "-"
    args = [f"--arm-id {a.arm}", "--run-dir %RUN%", f"--regime {r['regime']}", f"--encoder {r['encoder']}",
            "--train-npz %STG%\\data\\m5_multiscript_v1\\m5_luo_train.npz", "--render-npy %STG%\\exp\\FMD\\xs\\data\\backbone\\luo_train_render224.npy",
            f"--train-steps {r['steps']}", f"--save-every {r['save_every']}", "--batch-size 32 --grad-accum 16",
            "--learning-rate 8e-5 --enc-lr 2e-4 --enc-warmup 200 --seed 20261016 --num-workers 4 --lane vps"]
    if r["regime"] == "warm":
        args.append("--init-ckpt %STG%\\exp\\M5\\runs\\luo\\checkpoints\\checkpoint_000006.pt")
    if r["pe_weights"] != "-":
        args.append(f"--pe-weights {win(r['pe_weights'])}")
    if r["fm"] != "-":
        args.append(f"--fm {r['fm']} --verdict-file %STG%\\exp\\FMD\\xs\\verdicts\\verdict_{r['fm']}.json --verdict-every 10000")
    if r["repa_targets"] != "-":
        args.append(f"--repa-targets {win(r['repa_targets'])} --repa-unit-ids {win(r['repa_unit_ids'])} --repa-lambda {r['repa_lambda']}")
    if r["pseudo_npz"] != "-":
        args.append(f"--pseudo-npz {win(r['pseudo_npz'])} --pseudo-render-npy {win(r['pseudo_render'])}")
    nms = int(r["steps"]) // int(r["save_every"])
    L = [
        "@echo off",
        f"REM FMDX backbone arm {a.arm} ({r['regime']}, fm {r['fm']}), VPS RTX 4090 copy, generated by gen_vps_cmd.py (track 'Backbone build').",
        "set ROOT=$VPS_ROOT\\uhwr", "set PY=C:\\ProgramData\\miniconda3\\envs\\uhwr\\python.exe", "set STG=%ROOT%\\stage",
        "set CODE=%ROOT%\\code\\fmdx_backbone_v1",
        "set PYTHONPATH=%ROOT%\\winshim;%ROOT%\\repos\\nagamatsu\\src;%CODE%;%CODE%\\vendor;%STG%\\exp\\FMD\\xs\\code\\pydeps_timm",
        "set PYTHONIOENCODING=utf-8", "set PYTHONDONTWRITEBYTECODE=1",
        f"set RUN=%STG%\\exp\\FMD\\xs\\runs\\{a.arm}_vps", "set RACE=%STG%\\exp\\FMD\\xs\\race",
        "if not exist %RUN% mkdir %RUN%", "if not exist %RACE% mkdir %RACE%",
        "%PY% -c \"import hashlib,sys,os;os.chdir(r'%CODE%');bad=[l.split()[1] for l in open('SHA256SUMS.txt') if hashlib.sha256(open(l.split()[1],'rb').read()).hexdigest()!=l.split()[0]];print('code sha bad',bad);sys.exit(1 if bad else 0)\"",
        "if errorlevel 1 exit /b 31",
        "if exist %RUN%\\training_complete.json goto sample",
        f"mkdir %RACE%\\{a.arm} 2>nul && (echo vps %DATE% %TIME%> %RACE%\\{a.arm}\\owner.txt)",
        f"findstr /b /c:\"vps\" %RACE%\\{a.arm}\\owner.txt >nul",
        f"if errorlevel 1 (echo {{\"arm\":\"{a.arm}\",\"lane\":\"vps\",\"owner\":\"other lane\"}}> %RUN%\\RACE_LOST.json & exit /b 0)",
        "echo %DATE% %TIME% train start >> %RUN%\\job_history.txt",
        "%PY% -u %CODE%\\bb_train.py " + " ".join(args) + " >> %RUN%\\train_vps.log 2>&1",
        "if exist %RUN%\\GATE_FAIL (echo %DATE% %TIME% GATE_FAIL >> %RUN%\\job_history.txt & exit /b 0)",
        "if not exist %RUN%\\training_complete.json exit /b 32",
        ":sample",
        "if not exist %RUN%\\eval mkdir %RUN%\\eval",
        f"for %%M in ({' '.join(str(m) for m in range(1, nms + 1))}) do for %%S in (casia_zh casia_en hpl_tamil iam) do (",
        "  if not exist %RUN%\\eval\\val__%%S__ms%%M_preds.json (",
        "    %PY% -u %CODE%\\bb_sample.py --ckpt %RUN%\\bb_ms%%M.pt --render %STG%\\exp\\FMD\\xs\\data\\backbone\\val250_%%S_render224.npz --gt-npz %STG%\\data\\m5_multiscript_v1\\m5_val_%%S.npz --subset 250 --subset-seed 0 --seed 0 --sampling-timesteps 50 --ddim-eta 0 --batch-size 250 --out %RUN%\\eval\\val__%%S__ms%%M_preds.npz >> %RUN%\\sample_vps.log 2>&1",
        "  )",
        ")",
        f"if not exist %RUN%\\eval\\val__iam__ms{nms}_preds.json exit /b 33",
        "echo %DATE% %TIME% end (scoring + selection on CLUSTER-A after pull) >> %RUN%\\job_history.txt",
        "exit /b 0",
    ]
    print("\r\n".join(L), end="\r\n")


if __name__ == "__main__":
    main()
