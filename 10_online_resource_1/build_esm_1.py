#!/usr/bin/env python3
"""build_esm_1.py: supplementary_v12.1.tex -> ESM_1.tex (Online Resource 1, Springer Supplementary Information).

Inputs (sha256 checked): supplementary_v12.1.tex and paper_inkbridge_v12.2.tex (source of the title/author block).
The title block and the preamble change, and dagger note markers become superscript lower-case letters (6 edits). Otherwise unchanged; compiled with references.bib v12.3.
Originally: only the title block and the preamble change (heading 'Online Resource 1', article title, journal name, author names,
affiliation and e-mail of the corresponding author, PDF metadata, separate figure numbering). The content is unchanged.
Usage: python build_esm_1.py IN_SUPP_TEX IN_PAPER_TEX OUT_TEX
"""
import sys, re, hashlib
SUPP_SHA = "9a349b74a14872df"; PAPER_SHA = "8cfb46c40456c53e"
JOURNAL = "International Journal on Document Analysis and Recognition"   # journal name as given in the task and the guideline page
def die(m): sys.exit("BUILD FAILED: " + m)
sup_b = open(sys.argv[1], "rb").read(); pap_b = open(sys.argv[2], "rb").read()
if not hashlib.sha256(sup_b).hexdigest().startswith(SUPP_SHA): die("supplement sha256 mismatch")
if not hashlib.sha256(pap_b).hexdigest().startswith(PAPER_SHA): die("paper sha256 mismatch")
S = sup_b.decode("utf-8"); P = pap_b.decode("utf-8")

# ---- author block of the paper ----
title = re.search(r"\\title\[[^\]]*\]\{(.*)\}\n", P).group(1)
authors = re.findall(r"\\author(\*?)\[([\d,]+)\]\{\\fnm\{([^}]*)\} \\sur\{([^}]*)\}\}(?:\\email\{([^}]*)\})?", P)
if len(authors) != 6: die(f"expected 6 authors, found {len(authors)}")
corr = [a for a in authors if a[0] == "*"]
if len(corr) != 1 or not corr[0][4]: die("corresponding author / e-mail not found")
_, corr_aff, cf, cs, corr_mail = corr[0]
names = [f"{f} {s}" for _, _, f, s, _ in authors]
affs = {}
for num, txt in re.findall(r"\\affil\*?\[(\d)\]\{(.*)\}\n", P):
    g = lambda k: (re.search(r"\\" + k + r"\{((?:[^{}]|\{[^{}]*\})*)\}", txt) or [None, None])[1]
    parts = [g("orgdiv"), g("orgname"), g("street"), g("city"), g("postcode"), g("country")]
    affs[num] = ", ".join(p for p in parts if p)
corr_affs = [affs[n] for n in corr_aff.split(",")]
if title not in S: die("paper title differs from the title used in the supplement")
# section titles of the paper that the supplement names must exist in the paper
paper_secs = set(re.findall(r"\\(?:sub)?section\{([^}]*)\}", P))
for name in set(re.findall(r"Section ``([^']+)''", S)):
    if name not in paper_secs: die("supplement names a paper section that does not exist: " + name)

# ---- replace the title block ----
old_block = re.search(r"\\title\{Supplementary Material for:.*?\\maketitle\n", S, re.S)
if not old_block: die("title block not found")
new_block = "\n".join([
    r"\begin{center}",
    r"{\LARGE\bfseries Online Resource 1}\\[8pt]",
    r"{\large Supplementary Information for the article}\\[4pt]",
    r"{\Large\bfseries " + title + r"}\\[8pt]",
    r"{\large\itshape " + JOURNAL + r"}\\[10pt]",
    r"{\large " + ", ".join(names[:3]) + r",\\ " + ", ".join(names[3:]) + r"}\\[10pt]",
    r"\end{center}",
    r"\noindent\textbf{Corresponding author:} " + f"{cf} {cs}, " + "; ".join(corr_affs) + r". E-mail: \texttt{" + corr_mail + r"}",
    r"\par\medskip\hrule\medskip", ""])
S2 = S.replace(old_block.group(0), new_block)
# ---- preamble: PDF metadata, separate figure numbering ----
anchor = r"\renewcommand{\thetable}{S\arabic{table}}" + "\n"
if S2.count(anchor) != 1: die("preamble anchor")
meta = (r"\renewcommand{\thefigure}{S\arabic{figure}}" + "\n" +
        r"\pdfinfo{/Title (Online Resource 1: " + title + r") /Author (" + ", ".join(names) + r") /Subject (Supplementary Information, " + JOURNAL + ")}\n")
S2 = S2.replace(anchor, anchor + meta)
head = "% ESM_1.tex: Online Resource 1 (Supplementary Information). Generated by build_esm_1.py from supplementary_v12.1.tex; title block from paper_inkbridge_v12.2.tex. Do not edit by hand.\n"
S2 = head + S2
# content check: everything after the title block is byte-identical
tail0 = S[old_block.end():]
if not S2.endswith(tail0): die("content after the title block changed")
# ---- table note markers: superscript lower-case letters instead of daggers (IJDAR table-note rule, as in the paper) ----
EDITS = [
 (r"are exploratory and marked $^{\dagger}$.", r"are exploratory and marked by a table note.", "Section S1: 'marked dagger' reworded (as in the paper)."),
 (r"$\fnot{ur}$ (no warm stage)$^{\dagger}$ & $-0.0180$ & no / no & $-0.0176$", r"$\fnot{ur}$ (no warm stage)$^{a}$ & $-0.0180$ & no / no & $-0.0176$", "Table S3: row marker dagger replaced by superscript a."),
 (r"first seed: training seed 20261034 alone; $^{b}$ $-0.01247$.}", r"first seed: training seed 20261034 alone; $^{a}$ one seed; $^{b}$ $-0.01247$.}", "Table S3: note a added to the note beneath the table."),
 (r"$\fnot{ur}$ (no warm stage)$^{\dagger}$ & $-0.0256$ & 4/6 & no", r"$\fnot{ur}$ (no warm stage)$^{a}$ & $-0.0256$ & 4/6 & no", "Table S9: row marker dagger replaced by superscript a."),
 (r"\par\smallskip{\scriptsize Min.\ AIoU lo: lowest AIoU lower bound over the six sets;", r"\par\smallskip{\scriptsize $^{a}$ One seed. Min.\ AIoU lo: lowest AIoU lower bound over the six sets;", "Table S9: note a added beneath the table."),
 (r"on all six non-Urdu sets$^{\dagger}$, but", r"on all six non-Urdu sets (fewer than three seeds, exploratory), but", "Section S5.3 running text: dagger replaced by its stated meaning."),
]
for old, new, desc in EDITS:
    if S2.count(old) != 1: die("ESM edit anchor not found once: " + old[:60])
    S2 = S2.replace(old, new)
if "dagger" in S2: die("dagger left in ESM")
import json
json.dump([d for _, _, d in EDITS], open(sys.argv[3] + ".changes.json", "w"), indent=1)
open(sys.argv[3], "w", encoding="utf-8").write(S2)
print("OK", len(S2), "| corresponding:", cf, cs, corr_mail, "| affs:", len(corr_affs))
